"""Re-export greenhouse.blend after editing it in Blender.

Workflow: open greenhouse.blend, edit geometry/materials (keep object names used by the viewer), then run
    blender -b greenhouse.blend -P export_greenhouse_asset.py
This writes greenhouse.glb only; greenhouse_meta.json (state-point anchors and flow paths) is kept as generated by
create_greenhouse_asset.py. To regenerate everything from code instead, run create_greenhouse_asset.py.
"""
from pathlib import Path

import bpy

out = Path(__file__).resolve().parent / "greenhouse.glb"
for o in bpy.data.objects:
    o.select_set(o.type in {"MESH", "EMPTY"} and not o.name.startswith(("Preview", "Sun")))
bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", use_selection=True, export_extras=True, export_apply=True,
                          export_yup=True, export_image_format="JPEG", export_jpeg_quality=82)
print("exported", out)
