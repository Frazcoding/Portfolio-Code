"""Re-export wlc_office.blend after editing it in Blender.

Workflow: open wlc_office.blend, edit geometry/materials (keep object names used by the viewer), then run
    blender -b wlc_office.blend -P export_wlc_asset.py
This writes wlc_office.glb only; wlc_office_meta.json (state-point anchors and flow paths) is kept as generated by
create_wlc_asset.py. To regenerate everything from code instead, run create_wlc_asset.py.
"""
from pathlib import Path

import bpy

out = Path(__file__).resolve().parent / "wlc_office.glb"
for o in bpy.data.objects:
    o.select_set(o.type in {"MESH", "EMPTY"} and not o.name.startswith(("Preview", "Sun")))
bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", use_selection=True, export_extras=True, export_apply=True,
                          export_yup=True, export_image_format="JPEG", export_jpeg_quality=82)
print("exported", out)
