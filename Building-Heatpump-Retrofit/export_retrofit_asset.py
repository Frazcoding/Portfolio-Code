"""Re-export retrofit_plant.blend after editing it in Blender.

Workflow: open retrofit_plant.blend, edit geometry/materials (keep object names used by the viewer), then run
    blender -b retrofit_plant.blend -P export_retrofit_asset.py
This writes retrofit_plant.glb only; retrofit_plant_meta.json (state-point anchors and flow paths) is kept as generated by
create_retrofit_asset.py. To regenerate everything from code instead, run create_retrofit_asset.py.
"""
from pathlib import Path

import bpy

out = Path(__file__).resolve().parent / "retrofit_plant.glb"
for o in bpy.data.objects:
    o.select_set(o.type in {"MESH", "EMPTY"} and not o.name.startswith(("Preview", "Sun")))
bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", use_selection=True, export_extras=True, export_apply=True,
                          export_yup=True, export_image_format="JPEG", export_jpeg_quality=82)
print("exported", out)
